#!/bin/bash
# Build phase: encrypts the astrology rules (AstroData/*.json) into the app bundle as .bin files
# (16-byte IV + AES-256-CBC ciphertext) with a fresh random key each build, and writes that key,
# XOR-masked, to a generated Swift file (AstroDataKey.swift) that the app compiles.
#
# This keeps the files unreadable to anyone who simply unzips the IPA. The key is inside the app,
# so it does not stop someone determined enough to disassemble it.
set -euo pipefail

src="$SRCROOT/AstroData"
dest="$TARGET_BUILD_DIR/$UNLOCALIZED_RESOURCES_FOLDER_PATH"
gen="$DERIVED_FILE_DIR/AstroDataKey.swift"
mkdir -p "$dest" "$DERIVED_FILE_DIR"

key=$(openssl rand -hex 32)
mask=$(openssl rand -hex 32)

for name in house_behaviour planet_house_rules; do
  iv=$(openssl rand -hex 16)
  { printf '%s' "$iv" | xxd -r -p; openssl enc -aes-256-cbc -K "$key" -iv "$iv" -in "$src/$name.json"; } > "$dest/$name.bin"
done

masked=""; maskBytes=""
for ((i = 0; i < 64; i += 2)); do
  k=$((16#${key:i:2})); m=$((16#${mask:i:2}))
  masked+="$(printf '0x%02x, ' $((k ^ m)))"
  maskBytes+="$(printf '0x%02x, ' "$m")"
done

cat > "$gen" <<SWIFT
// Generated by Scripts/encrypt-astro-data.sh. Do not edit.
enum AstroDataKey {
    static let masked: [UInt8] = [${masked}]
    static let mask: [UInt8] = [${maskBytes}]
}
SWIFT
